import { CampaignPlanner, Translator } from '../interfaces';
import { CampaignPlanInput, CampaignPlanResult, TranslationInput, TranslationResult } from '@/types';

export class DemoCampaignPlanner implements CampaignPlanner {
  async generatePlan(input: CampaignPlanInput): Promise<CampaignPlanResult> {
    // Deterministic demo plan based on input
    const offerType = input.allowed_offer_types.includes('percentage_discount')
      ? 'percentage_discount'
      : input.allowed_offer_types[0] ?? 'no_offer';

    const offerValue = offerType === 'percentage_discount' ? 15 : offerType === 'fixed_discount' ? 5000 : null;

    return {
      rationale: `[DEMO FALLBACK — not generated by Gemini] Based on your segment of ${input.segment_summary.total_eligible} at-risk customers with a typical visit cadence of ${Math.round(input.segment_summary.median_cadence_days)} days, a targeted winback offer sent via ${input.channel} can encourage a return visit.`,
      target_segment_description: `At-risk customers who haven't visited in over ${Math.round(input.segment_summary.days_since_typical_purchase)} days on average.`,
      offer_type: offerType,
      offer_value: offerValue,
      offer_description:
        offerType === 'percentage_discount'
          ? `${offerValue}% off your next purchase`
          : offerType === 'fixed_discount'
            ? `₹${((offerValue ?? 0) / 100).toFixed(0)} off your next visit`
            : 'Special thank-you offer for loyal customers',
      message_draft: `Hi {name}! We miss you at ${input.merchant_type === 'cafe' ? 'our café' : 'our store'}! Come back and enjoy a special offer just for you. Valid this week only.`,
      experiment_duration_days: 14,
      assumptions: [
        'This is a demo plan. Connect Gemini API for AI-generated campaigns.',
        `Budget: ₹${(input.budget_minor / 100).toFixed(2)}`,
        `Channel: ${input.channel}`,
      ],
      warnings: ['⚠️ This plan was generated by the demo fallback, not by Gemini AI.'],
      source: 'demo_fallback',
    };
  }
}

