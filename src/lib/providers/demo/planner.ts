/**
 * Deterministic demo planner. Used only when no Gemini key is configured, or when the merchant
 * explicitly chooses it after a Gemini failure. Always labelled `demo_fallback`; never claims to
 * be model output. It keeps the merchant's configured offer and writes copy for exactly it.
 */
import { minorToRupeesInput, type Offer } from '@/lib/campaigns/rules';
import type { CampaignPlanInput, CampaignPlanResult } from '@/lib/planner/types';
import type { CampaignPlanner } from '../interfaces';

const rupees = (minor: number) => `₹${minorToRupeesInput(minor)}`;

function offerSentence(offer: Offer): string {
  switch (offer.type) {
    case 'no_offer': return 'We would love to see you again.';
    case 'percentage_discount':
      return `Enjoy ${offer.percent}% off your next order${offer.max_discount_minor ? ` (up to ${rupees(offer.max_discount_minor)})` : ''}.`;
    case 'fixed_discount': return `Enjoy ${rupees(offer.amount_minor)} off your next order.`;
    case 'free_item': return `Enjoy a free ${offer.item_name} on your next visit.`;
  }
}

export function demoMessage(offer: Offer): string {
  const parts = ['Hi! We miss you and would love to see you again.', offerSentence(offer)];
  if (offer.type !== 'no_offer') {
    if (offer.minimum_order_value_minor) parts.push(`Valid on orders of ${rupees(offer.minimum_order_value_minor)} or more.`);
    if (offer.expiry_days) parts.push(`Valid for ${offer.expiry_days} day${offer.expiry_days === 1 ? '' : 's'}.`);
    parts.push('Just show this message when you visit.');
  }
  return parts.join(' ');
}

export class DemoCampaignPlanner implements CampaignPlanner {
  constructor(private readonly reason: string) {}

  async generatePlan(input: CampaignPlanInput): Promise<CampaignPlanResult> {
    const { segment } = input;
    const rhythm = segment.avg_cadence_days === null
      ? ''
      : ` Their typical gap between visits is about ${segment.avg_cadence_days} days, and it has now been about ${segment.avg_days_since_purchase} days.`;
    return {
      rationale: `Demo draft, not generated by Gemini. ${segment.eligible} eligible customers in "${segment.label}".${rhythm} A friendly reminder with your configured offer is a low-risk way to bring them back.`,
      target_segment_description: `${segment.label}: ${segment.description}`,
      offer: input.current_offer,
      message_draft: demoMessage(input.current_offer),
      experiment_duration_days: 14,
      assumptions: [
        'This is a fixed template, not a tailored AI plan.',
        'Your configured offer is used unchanged.',
        'The message is English; translation is a separate step.',
      ],
      warnings: ['Demo fallback: this plan was not generated by Gemini.'],
      source: 'demo_fallback',
      model: null,
      fallback_reason: this.reason,
    };
  }
}
