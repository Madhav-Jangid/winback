import { describe, expect, it } from 'vitest';
import { validatePlan, contextFromInput } from '@/lib/planner/validate';
import { makePlanInput } from '@/test/fixtures/plan-input';
import { DemoCampaignPlanner } from './demo/planner';
import { GeminiCampaignPlanner } from './gemini/planner';
import { DemoTranslator } from './demo/translator';
import { SarvamTranslator } from './sarvam/translator';
import { selectPlanner, selectTranslator } from './factory';

describe('planner selection', () => {
  it.each([[undefined], [''], ['   ']])('AI-05: missing key (%j) selects the labelled demo planner', async (key) => {
    const selection = selectPlanner({ GEMINI_API_KEY: key, GEMINI_MODEL: undefined });
    expect(selection.live).toBe(false);
    expect(selection.planner).toBeInstanceOf(DemoCampaignPlanner);
    const plan = await selection.planner.generatePlan(makePlanInput());
    expect(plan).toMatchObject({ source: 'demo_fallback', model: null });
    expect(plan.fallback_reason).toMatch(/GEMINI_API_KEY is not configured/);
    expect(plan.warnings.join(' ')).toMatch(/not generated by Gemini/);
  });

  it('selects Gemini when a key is configured', () => {
    const selection = selectPlanner({ GEMINI_API_KEY: 'k', GEMINI_MODEL: 'gemini-3.8-flash' });
    expect(selection.live).toBe(true);
    expect(selection.planner).toBeInstanceOf(GeminiCampaignPlanner);
  });
});

describe('translator selection', () => {
  it.each([[undefined], [''], ['   ']])('SA-04: missing key (%j) selects the demo translator, labelled as demo output', async (key) => {
    const selection = selectTranslator({ SARVAM_API_KEY: key, SARVAM_MODEL: undefined });
    expect(selection.live).toBe(false);
    expect(selection.translator).toBeInstanceOf(DemoTranslator);
    const result = await selection.translator.translate({ text: 'We miss you!', target_language: 'hi' });
    // It does not pretend to translate: same text, never labelled as Sarvam.
    expect(result).toMatchObject({ translated_text: 'We miss you!', source: 'demo_fallback', model: null });
    expect(result.fallback_reason).toMatch(/SARVAM_API_KEY is not configured/);
  });

  it('selects Sarvam when a key is configured', () => {
    const selection = selectTranslator({ SARVAM_API_KEY: 'k', SARVAM_MODEL: 'sarvam-translate:v1' });
    expect(selection.live).toBe(true);
    expect(selection.translator).toBeInstanceOf(SarvamTranslator);
  });
});

describe('demo planner', () => {
  it.each([
    ['percentage', { type: 'percentage_discount', percent: 15, max_discount_minor: 8_000, minimum_order_value_minor: 20_000, expiry_days: 7 }],
    ['fixed', { type: 'fixed_discount', amount_minor: 2_500 }],
    ['free item', { type: 'free_item', item_name: 'pastry with any coffee', item_cost_minor: 4_000, expiry_days: 1 }],
    ['no offer', { type: 'no_offer' }],
  ])('writes a %s message that passes the same validation as model output', async (_label, offer) => {
    const input = makePlanInput({ offer, budget_minor: 500_000, channel: 'sms' });
    const plan = await new DemoCampaignPlanner('test').generatePlan(input);
    const result = validatePlan(plan, contextFromInput(input));
    expect(result.ok, result.ok ? '' : result.reason).toBe(true);
    expect(plan.message_draft.length).toBeLessThanOrEqual(320);
    expect(plan.offer).toEqual(input.current_offer); // never changes the merchant's offer
    expect(plan).toMatchObject({ source: 'demo_fallback', model: null, fallback_reason: 'test' });
  });

  it('is deterministic and never invents an expiry', async () => {
    const input = makePlanInput();
    const a = await new DemoCampaignPlanner('x').generatePlan(input);
    const b = await new DemoCampaignPlanner('x').generatePlan(input);
    expect(a).toEqual(b);
    expect(a.message_draft).not.toMatch(/valid for|expires|only/i);
  });
});
